#!/usr/bin/env node
/**
 * Make the web export installable to a phone home screen.
 *
 * `expo export --platform web` with output: "static" emits no web manifest —
 * manifest generation belonged to the webpack config Expo no longer uses, so
 * the `web` block in app.config.ts is read for native concerns and ignored
 * here. Without one, "Add to Home Screen" produces a bookmark rather than an
 * app: the browser chrome stays, the label is the URL, and the icon is a
 * screenshot of the page.
 *
 * This writes the manifest and an icon, then injects the tags Expo's generated
 * HTML lacks. It runs over every .html file, not just index.html, because the
 * static export emits one per route and a phone can install from whichever the
 * user happens to be on.
 *
 *   node scripts/make-installable.mjs dist
 */
import { readFileSync, writeFileSync, readdirSync, statSync } from 'node:fs';
import { join, extname } from 'node:path';

const DIST = process.argv[2] ?? 'dist';

const MANIFEST = {
  name: 'LUMEN',
  short_name: 'LUMEN',
  description:
    'Report road damage from a photograph. Computer-vision detection, severity scoring and tracked repair.',
  start_url: '/',
  // standalone is what removes the address bar; without it the install is
  // indistinguishable from a bookmark.
  display: 'standalone',
  orientation: 'portrait',
  background_color: '#0f172a',
  theme_color: '#1e2a78',
  lang: 'en',
  icons: [
    { src: '/icon.svg', sizes: 'any', type: 'image/svg+xml', purpose: 'any maskable' },
  ],
};

// SVG rather than the usual pair of PNGs: `sizes: "any"` covers every launcher
// size from one file, and it avoids committing binaries generated by a tool
// this project does not otherwise depend on.
const ICON = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 512 512">
  <rect width="512" height="512" rx="112" fill="#1e2a78"/>
  <path d="M256 104c-57 0-104 46-104 104 0 74 94 186 99 191a7 7 0 0 0 10 0c5-5 99-117 99-191 0-58-47-104-104-104zm0 148a44 44 0 1 1 0-88 44 44 0 0 1 0 88z" fill="#fff"/>
</svg>`;

writeFileSync(join(DIST, 'manifest.webmanifest'), JSON.stringify(MANIFEST, null, 2));
writeFileSync(join(DIST, 'icon.svg'), ICON);

const HEAD_TAGS = `
    <title>LUMEN</title>
    <link rel="manifest" href="/manifest.webmanifest"/>
    <link rel="icon" type="image/svg+xml" href="/icon.svg"/>
    <link rel="apple-touch-icon" href="/icon.svg"/>
    <meta name="theme-color" content="#1e2a78"/>
    <meta name="description" content="${MANIFEST.description}"/>
    <!-- iOS reads its own tags rather than the manifest: without these, Safari
         installs the page with the address bar still showing. -->
    <meta name="apple-mobile-web-app-capable" content="yes"/>
    <meta name="apple-mobile-web-app-title" content="LUMEN"/>
    <meta name="apple-mobile-web-app-status-bar-style" content="black-translucent"/>`;

function* htmlFiles(dir) {
  for (const entry of readdirSync(dir)) {
    const full = join(dir, entry);
    if (statSync(full).isDirectory()) yield* htmlFiles(full);
    else if (extname(entry) === '.html') yield full;
  }
}

let patched = 0;
for (const file of htmlFiles(DIST)) {
  let html = readFileSync(file, 'utf8');
  if (html.includes('manifest.webmanifest')) continue;
  html = html.replace('</head>', `${HEAD_TAGS}\n  </head>`);
  writeFileSync(file, html);
  patched++;
}

console.log(`installable: manifest + icon written, ${patched} HTML file(s) patched`);
